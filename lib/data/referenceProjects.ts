export function referenceProjectsForProgram(programId: string): ReferenceProject[] {
  return referenceProjects.filter((r) => r.programId === programId);
}

export interface SuccessPatternStats {
  quantifiedImpactPct: number;
  scalabilityPct: number;
  multiOrgPct: number;
  goalAlignmentPct: number;
  pilotDemoPct: number;
  total: number;
}

export function computeSuccessPatterns(projects: ReferenceProject[]): SuccessPatternStats {
  const total = projects.length || 1;
  const pct = (key: ReferenceProject["successFactors"][number]) =>
    Math.round((projects.filter((p) => p.successFactors.includes(key)).length / total) * 100);

  return {
    quantifiedImpactPct: pct("quantified-impact"),
    scalabilityPct: pct("scalability"),
    multiOrgPct: pct("multi-org"),
    goalAlignmentPct: pct("strong-goal-alignment"),
    pilotDemoPct: pct("pilot-demo"),
    total: projects.length,
  };
}
