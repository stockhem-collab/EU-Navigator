// npm run build:kommuner — every Swedish municipality → lib/data/kommuner.ts
// (committed): kommunkod, name, organisationsnummer, SKR kommungrupp and
// population. Sources:
// - data/raw/skr_kommungruppsindelning_*.xlsx: SKR's kommungruppsindelning
//   (skr.se, "Kommungruppsindelning 2023", sheet "Bilaga1 Lista alla kommuner")
// - data/raw/skolverket/skolverket_*.json: organisationsnummer of each
//   municipality as school organiser (npm run fetch:skolverket)
// - SCB's API, table BE0101N1 (Folkmängd 31 december), fetched here.
import fs from "node:fs";
import path from "node:path";
import ExcelJS from "exceljs";
import { latestRawFile, ROOT } from "../../lib/integrations/core/files";
import type { SkolverketRegister } from "../../lib/integrations/erasmus/municipal";
import { main } from "./run";

const POPULATION_YEAR = "2024";
const SCB = "https://api.scb.se/OV0104/v1/doris/sv/ssd/START/BE/BE0101/BE0101A/BefolkningNy";

/** Municipalities whose official name ends in "stad". */
const STAD = new Set([
  "Stockholm",
  "Göteborg",
  "Malmö",
  "Helsingborg",
  "Västerås",
  "Lidingö",
  "Solna",
  "Sundbyberg",
  "Vaxholm",
  "Landskrona",
  "Trollhättan",
  "Mölndal",
  "Borås",
]);

/** "Uppsala" → "Uppsala", "Linköping" → "Linköpings", "Borås" → "Borås". */
function genitive(name: string): string {
  if (name === "Falun") return "Falu";
  if (name === "Kalmar") return name;
  return /[aeiouyåäöé]$|[sxz]$/i.test(name) ? name : `${name}s`;
}

function officialName(name: string): string {
  if (name === "Gotland") return "Region Gotland";
  return `${genitive(name)} ${STAD.has(name) ? "stad" : "kommun"}`;
}

async function population(codes: string[]): Promise<Record<string, number>> {
  // SCB answers 503 now and then; try a few times.
  for (let attempt = 1; ; attempt++) {
    const res = await fetch(SCB, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({
        query: [
          { code: "Region", selection: { filter: "item", values: codes } },
          {
            code: "ContentsCode",
            selection: { filter: "item", values: ["BE0101N1"] },
          },
          {
            code: "Tid",
            selection: { filter: "item", values: [POPULATION_YEAR] },
          },
        ],
        response: { format: "json" },
      }),
    });
    if (res.ok) {
      const data = (await res.json()) as {
        data: { key: string[]; values: string[] }[];
      };
      return Object.fromEntries(data.data.map((d) => [d.key[0], Number(d.values[0])]));
    }
    if (attempt >= 5) throw new Error(`SCB: HTTP ${res.status}`);
    await new Promise((r) => setTimeout(r, 2000 * attempt));
  }
}

main(async () => {
  const skrFile = latestRawFile(/^skr_kommungruppsindelning_.*\.xlsx$/);
  const workbook = new ExcelJS.Workbook();
  await workbook.xlsx.readFile(skrFile);
  const sheet = workbook.worksheets.find((s) => /alla kommuner/i.test(s.name));
  if (!sheet) throw new Error(`${skrFile}: no sheet "Lista alla kommuner"`);
  const skr: { group: string; code: string; name: string; label: string }[] = [];
  sheet.eachRow((row, n) => {
    if (n === 1) return;
    const [group, code, name, , label] = (row.values as unknown[]).slice(1).map((v) => String(v ?? "").trim());
    if (/^\d{4}$/.test(code)) skr.push({ group, code, name, label });
  });

  const registerFile = latestRawFile(/^skolverket_.*\.json$/, "skolverket");
  const register = JSON.parse(fs.readFileSync(registerFile, "utf8")) as SkolverketRegister;
  const orgNumber = new Map(register.municipalities.map((m) => [m.municipalityCode, m.orgNumber]));
  const pop = await population(skr.map((k) => k.code));

  const rows = skr
    .map((k) => {
      const nr = orgNumber.get(k.code);
      if (!nr) throw new Error(`No organisationsnummer for ${k.name} (${k.code}) in ${registerFile}`);
      if (!pop[k.code]) throw new Error(`No population for ${k.name} (${k.code})`);
      return {
        kommunkod: k.code,
        name: k.name,
        officialName: officialName(k.name),
        orgNumber: `${nr.slice(0, 6)}-${nr.slice(6)}`,
        kommungrupp: k.group,
        kommungruppNamn: k.label,
        population: pop[k.code],
      };
    })
    .sort((a, b) => a.kommunkod.localeCompare(b.kommunkod));

  const out = path.join(ROOT, "lib", "data", "kommuner.ts");
  fs.writeFileSync(
    out,
    [
      "// Generated by npm run build:kommuner (scripts/import/kommuner.ts) from",
      `// ${path.basename(skrFile)} (SKR kommungruppsindelning), ${path.basename(registerFile)}`,
      `// (organisationsnummer) and SCB's population on 31 December ${POPULATION_YEAR}. Do not edit by hand.`,
      "",
      "export interface Kommun {",
      "  kommunkod: string;",
      '  /** "Uppsala" */',
      "  name: string;",
      '  /** "Uppsala kommun", "Stockholms stad" */',
      "  officialName: string;",
      "  orgNumber: string;",
      '  /** SKR kommungrupp code, e.g. "B3". */',
      "  kommungrupp: string;",
      '  /** e.g. "Större stad". */',
      "  kommungruppNamn: string;",
      "  population: number;",
      "}",
      "",
      `export const KOMMUNER_POPULATION_YEAR = ${POPULATION_YEAR};`,
      "",
      "export const KOMMUNER: Kommun[] = [",
      ...rows.map((r) => `  ${JSON.stringify(r)},`),
      "];",
      "",
    ].join("\n"),
  );
  console.log(`skriven fil ${path.relative(ROOT, out)} (${rows.length} kommuner)`);
});
